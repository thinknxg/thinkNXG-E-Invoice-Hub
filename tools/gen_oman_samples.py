"""Regenerate samples/oman/ from the test fixtures.

    python tools/gen_oman_samples.py [/path/to/pint-om-resources-1.0.1]

With the path (folders billing/ and sb/ of the official PINT OM resources, plus saxonche installed)
the official Schematron result is written next to each sample; without it that file says it did not run.
Everything produced is a TEST FIXTURE: invented parties, not certified or approved by any authority.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from thinknxg_einvoice_hub.compliance.registry import get_engine  # noqa: E402
from thinknxg_einvoice_hub.tests import oman_fixtures as F  # noqa: E402
from thinknxg_einvoice_hub.tests.mock_oman_provider import MockOmanProvider  # noqa: E402

NOTICE = ("TEST FIXTURE generated by thinkNXG E-Invoice Hub from invented data. It is not a real invoice and is not "
	"certified, approved or accepted by the Oman Tax Authority or any accredited service provider.")


def main(resources=None):
	out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "samples", "oman")
	os.makedirs(out, exist_ok=True)
	settings = {"official_validation": "if_configured"}
	if resources:
		settings.update(schematron_dir=os.path.join(resources, "billing"), selfbilling_schematron_dir=os.path.join(resources, "sb"))
	engine = get_engine("om_pint_om", settings)
	provider = MockOmanProvider({})
	original_uuid = None
	cases = [("standard_invoice", F.standard), ("zero_rated_invoice", F.zero_rated), ("exempt_invoice", F.exempt),
		("credit_note", None), ("b2c_simplified_invoice", F.b2c), ("usd_invoice", F.foreign_currency)]
	index = []
	for name, build in cases:
		source = F.credit_note(original_uuid) if name == "credit_note" else build()
		canonical = engine.normalize_invoice(source)
		hub_issues = engine.validate(canonical)
		document = engine.generate_document(canonical)
		official = engine.validate_document(document, canonical)
		if name == "standard_invoice":
			original_uuid = document["document_uuid"]
		response = {k: v for k, v in provider.submit_document(document["content"], {}).items() if k != "raw"}
		folder = os.path.join(out, name)
		os.makedirs(folder, exist_ok=True)
		dump = lambda fn, data: json.dump(data, open(os.path.join(folder, fn), "w", encoding="utf-8"), indent=2,
			ensure_ascii=False, sort_keys=True, default=str)
		dump("1_input.json", {"_notice": NOTICE, **source})
		dump("2_canonical.json", {"_notice": NOTICE, **canonical})
		with open(os.path.join(folder, "3_pint_om.xml"), "w", encoding="utf-8") as f:
			f.write(document["content"].replace("?>\n", f"?>\n<!-- {NOTICE} -->\n", 1))
		dump("4_validation.json", {"hub_rules": hub_issues, "official_schematron": official,
			"official_schematron_ran": bool(resources) and not any(i["rule_id"] == "EIH-OM-090" for i in official)})
		dump("5_mock_provider_response.json", {"_notice": "Response of the MOCK provider used in tests, not a real provider.",
			**response})
		index.append((name, document["document_uuid"], len([i for i in official if i["severity"] == "Error"])))
	print("\n".join(f"{n}: uuid {u}, official errors {e}" for n, u, e in index))


if __name__ == "__main__":
	main(sys.argv[1] if len(sys.argv) > 1 else None)
