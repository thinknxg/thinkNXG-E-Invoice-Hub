"""Oman identifiers: VATIN, Peppol participant ID, Invoice UUID and Seller UUID.

Both UUIDs are version 5 with the fixed OTA namespace [OM-SRA 10.2.3, Appendix D.1].
The methods below reproduce the published examples:

* Seller UUID ``1.1|01|INVOICE-01|بائع|OM1234567891|2026-05-13|18:31:00|302.340|14.520``
  -> ``454cb7ea-f1f7-5b69-9e0b-756f002efa52`` (OM SRA Appendix D table).
* Invoice UUID ``0248 5060012349998 380 33445566 2026-01-13 100.00 105.00``
  -> ``7b95376b-e63c-50e0-a0e9-62f2092288a6``. OM SRA 1.0.3 prints a different output for this
  input; that printed value does not follow from the stated method, which phax/peppol-om
  (OpenPeppol's reference Java library author) also records.
"""

import re
import uuid

from thinknxg_einvoice_hub.compliance.oman import constants as C

#: VATIN: "OM" followed by 10 digits (OM SRA 10.3.1 example 0248:OM1100003554)
VATIN_PATTERN = r"^OM\d{10}$"
UUID_V5_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-5[0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$")
#: whitespace stripped from UUID inputs: space, tab, CR, LF
_WS = " \t\r\n"


def clean_vatin(value):
	if not value:
		return None
	return re.sub(r"[\s\-]", "", str(value)).upper()


def is_vatin(value, pattern=VATIN_PATTERN):
	return bool(value and re.match(pattern, value))


def participant_id(address, scheme=C.ENDPOINT_SCHEME):
	"""Peppol participant identifier, e.g. ``0248:OM1100003554``."""
	return f"{scheme}:{address}" if address else None


def _ns(namespace=None):
	return uuid.UUID(namespace or C.UUID_NAMESPACE)


def invoice_uuid_input(scheme, seller_endpoint, type_code, number, issue_date, tax_total, tax_inclusive, pm_total=None):
	"""The "name" for BTOM-002: values trimmed, empty ones dropped, joined by single blanks.

	Amounts must be passed exactly as written in the XML (e.g. ``"105.000"``), because the
	accredited provider recomputes the UUID from the document text.
	"""
	parts = (scheme, seller_endpoint, type_code, number, issue_date, tax_total, tax_inclusive, pm_total)
	return " ".join(s for s in (str(p).strip(_WS) for p in parts if p is not None) if s)


def invoice_uuid(*args, namespace=None, **kwargs):
	"""Invoice UUID (BTOM-002). Arguments as :func:`invoice_uuid_input`."""
	return str(uuid.uuid5(_ns(namespace), invoice_uuid_input(*args, **kwargs)))


def seller_uuid_input(invoice_type, number, seller_name, vatin, issue_date, issue_time, total, vat_total=None,
		qr_version=C.QR_VERSION):
	"""The "name" for BTOM-004: QR fields joined by ``|`` and upper-cased (OM SRA Appendix D.1).

	``invoice_type`` is ``"01"`` (full / simplified) or ``"02"`` (profit margin, where ``total``
	is BTOM-020 and there is no VAT total).
	"""
	parts = [qr_version, invoice_type, number, seller_name, vatin, issue_date, issue_time, total]
	if invoice_type != C.QR_INVOICE_TYPES["PROFIT_MARGIN"]:
		parts.append(vat_total)
	return "|".join("" if p is None else str(p) for p in parts).upper()


def seller_uuid(*args, namespace=None, **kwargs):
	"""Seller UUID (BTOM-004), generated by the seller (C1) for the QR code and the invoice."""
	return str(uuid.uuid5(_ns(namespace), seller_uuid_input(*args, **kwargs)))


def is_uuid_v5(value):
	return bool(value and UUID_V5_RE.match(value))
